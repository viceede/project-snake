static const uint8_t FONT_SPACE[7] = {0,0,0,0,0,0,0};

const uint8_t *core_font_glyph(char c, int *w, int *h) {
    static uint8_t buf[7];
    *w = 5;
    *h = 7;

    if (c >= '0' && c <= '9') return FONT_DIGITS[c - '0'];
    if (c >= 'A' && c <= 'Z') return FONT_UPPER[c - 'A'];
    if (c >= 'a' && c <= 'z') return FONT_UPPER[c - 'a'];

    for (int i = 0; i < 7; ++i) buf[i] = FONT_SPACE[i];
    return buf;
}